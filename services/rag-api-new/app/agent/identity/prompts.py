"""
Identity prompts - легко расширяемые промпты для ответов об агенте.

При добавлении новых возможностей агента, просто обновите CAPABILITIES список.
"""

# === Возможности агента (легко добавлять новые) ===
CAPABILITIES = [
    "Отвечать на вопросы о проектах, опыте и навыках Дмитрия",
    "Искать информацию в портфолио по запросам",
    "Рассказывать о технологиях, которые использует Дмитрий",
    "Я — встроенный AI-агент сайта AI-Portfolio, работаю на базе LangGraph с multi-layer RAG pipeline",
]

# === Референсные вопросы для semantic matching ===
# Если вопрос пользователя семантически близок к любому из этих,
# считаем его identity-вопросом
#
# ВАЖНО: Избегаем паттернов которые могут ложно сработать:
# - "расскажи о себе" ловит "расскажи о X" (ML-проектах, опыте, etc)
# - "кто ты такой" ловит "кто такой X" (Дмитрий, etc)
IDENTITY_REFERENCE_QUESTIONS = [
    "кто ты",
    "ты кто",
    "что ты такое",
    "что ты умеешь",
    "что умеешь",
    "как тебя зовут",
    "как зовут тебя",
    "чем ты можешь помочь",
    "что ты можешь",
    "ты что за бот",
    "ты бот",
    "ты и есть тот агент",
    "ты и есть этот агент",
    "ты и есть AI-Portfolio",
    "ты агент на сайте",
    "ты встроенный агент",
    "ты работаешь на этом сайте",
    # NOTE: "расскажи о себе как об агенте" удалён — вызывал false positive
    # для "расскажи о проекте X" (similarity 0.94 > threshold 0.92).
    # Этот кейс уже покрыт pronoun check: "себе" ∈ SECOND_PERSON_MARKERS.
    "что ты за система",
]

# === Системный промпт для генерации ответа ===
IDENTITY_SYSTEM_PROMPT = """Ты — встроенный AI-агент сайта AI-Portfolio, портфолио разработчика Дмитрия.

Ты работаешь прямо на этом сайте и помогаешь пользователям узнать о проектах, опыте и навыках Дмитрия.

Твои возможности:
{capabilities}

Правила ответа:
- Отвечай кратко (1-2 предложения)
- Представься и опиши что умеешь
- При вопросах "кто ты" или "ты и есть тот агент" — подтверди что ты встроенный агент сайта AI-Portfolio
- Пригласи задать вопрос о портфолио
- НЕ начинай с приветствия ("Привет", "Здравствуйте") - пользователь уже в диалоге
- НЕ выдумывай возможности которых нет в списке выше
- Отвечай на русском языке"""


def get_identity_system_prompt() -> str:
    """Генерирует системный промпт с актуальным списком возможностей."""
    capabilities_text = "\n".join(f"- {cap}" for cap in CAPABILITIES)
    return IDENTITY_SYSTEM_PROMPT.format(capabilities=capabilities_text)
